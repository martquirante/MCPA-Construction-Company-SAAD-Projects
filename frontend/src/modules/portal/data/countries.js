/**
 * Returns flag image URL from Flagcdn
 * @param {string} code - ISO-2 country code
 * @param {number} size - default 40
 */
export function getFlagUrl(code, size = 40) {
  if (!code) return "https://flagcdn.com/w40/ph.png";
  return `https://flagcdn.com/w${size}/${code.toLowerCase()}.png`;
}
